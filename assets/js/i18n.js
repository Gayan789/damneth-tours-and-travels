/* ==========================================================================
   Damneth Tours & Travels: languages
   Shows the site in English, German, French, Russian or Hebrew. The pages are
   written in English; each piece of text carries a key (data-i18n, and
   data-i18n-attr for alt, aria-label…), and the other languages come from small
   bundles in assets/i18n/<lang>/ made by tools/i18n.mjs. Runs before main.js.

   window.i18n
     lang             the language the page is showing now
     set(lang)        switch language (saved for the next visit)
     t(name, vars)    a message from main.js in the current language
     label(value)     a trip item's name (journeys, places…) in the current language
     refresh(el)      put a piece of text main.js replaced back in the current language
   Fires "i18n:change" on document after the page has switched.
   ========================================================================== */
(() => {
  'use strict';

  const LANGS = {
    en: { tag: 'en-GB', dir: 'ltr', flag: 'gb', name: 'English', english: 'English' },
    de: { tag: 'de', dir: 'ltr', flag: 'de', name: 'Deutsch', english: 'German' },
    fr: { tag: 'fr', dir: 'ltr', flag: 'fr', name: 'Français', english: 'French' },
    ru: { tag: 'ru', dir: 'ltr', flag: 'ru', name: 'Русский', english: 'Russian' },
    he: { tag: 'he', dir: 'rtl', flag: 'il', name: 'עברית', english: 'Hebrew' },
  };
  const STORE_KEY = 'damneth-lang';
  const root = document.documentElement;
  const page = root.getAttribute('data-i18n-page') || '';
  const bundlesFor = page ? ['common', page] : ['common'];

  /* <en> generated by tools/i18n.mjs from i18n/en/strings.json */
  var EN = {
    "menu_open": "Open menu",
    "menu_close": "Close menu",
    "trip_dock": "My trip",
    "dock_label": {
      "one": "My trip: {n} pick",
      "other": "My trip: {n} picks"
    },
    "dock_send_on": "Send on",
    "new_tab": "(opens in a new tab)",
    "dock_quote": "Get a free quote",
    "dock_clear": "Clear my trip",
    "picks_empty": "Nothing added yet.",
    "pick_remove": "Remove {item} from my trip",
    "trip_so_far": "Your trip so far: {items}. We’ll add these to your quote request.",
    "toggle_on": "Added to my trip",
    "toggle_off": "Add to my trip",
    "announce_added": "{item} added to your trip.",
    "announce_removed": "{item} removed from your trip.",
    "announce_replaces": "{item} replaces {previous} as your journey.",
    "announce_cleared": "Your trip has been cleared.",
    "err_name": "Please tell us your name so we know who we’re planning for.",
    "err_email": "That email doesn’t look quite right. Please check it, or leave it blank.",
    "err_travellers": "Please enter a number of travellers between 1 and 60.",
    "form_check": "Please check the highlighted field before sending.",
    "form_whatsapp": "WhatsApp should now open in a new tab with your details filled in. Just press send and we’ll reply soon.",
    "form_email": "Your email app should now open with your details filled in. If nothing happens, email us at {email}.",
    "filter_all_regions": {
      "one": "Showing all {n} region.",
      "other": "Showing all {n} regions."
    },
    "filter_some_regions": {
      "one": "Showing {n} region: {name}.",
      "other": "Showing {n} regions: {name}."
    },
    "filter_all_items": {
      "one": "Showing all {n} item.",
      "other": "Showing all {n} items."
    },
    "filter_some_items": {
      "one": "Showing {n} item: {name}.",
      "other": "Showing {n} items: {name}."
    },
    "filter_all_guides": {
      "one": "Showing all {n} guide.",
      "other": "Showing all {n} guides."
    },
    "filter_some_guides": {
      "one": "Showing {n} guide: {name}.",
      "other": "Showing {n} guides: {name}."
    },
    "lightbox_photo": "Photo {n} of {total}: {title}",
    "lightbox_video": "Video {n} of {total}: {title}",
    "lightbox_video_label": "Video: {alt}"
  };
  /* </en> */

  /* ---------- Units: the same rules as tools/lib/units.mjs ---------- */
  // A unit's text keeps its inline markup as numbered placeholders: <1>…</1> is an element whose
  // words are translated with the sentence, <2/> one that is kept as it is (icon, price, number).
  // The numbering must match the build's, so these lists and isOpaque() mirror units.mjs.
  const INLINE = new Set(['a', 'strong', 'em', 'b', 'i', 'span', 'small', 'br', 'abbr', 'time', 'sup', 'sub', 'mark', 'q', 'cite', 'bdi', 's', 'u', 'wbr', 'label', 'button']);
  const OPAQUE_TAGS = new Set(['svg', 'img', 'br', 'wbr', 'video', 'audio', 'picture', 'input', 'select', 'textarea', 'iframe', 'canvas', 'object']);
  const SKIP = new Set(['script', 'style', 'template', 'svg', 'noscript', 'head']);
  const LETTER = /\p{L}/u;
  const ENTITY = { amp: '&', lt: '<', gt: '>', nbsp: ' ' };
  const TOKEN = /<(\/?)(\d+)(\/?)>|&(amp|lt|gt|nbsp);|[^<&]+|[<&]/g;

  const isFixedKey = (key) => /^(cms|t):/.test(key || '');

  const hasLetters = (el) => Array.from(el.childNodes).some((child) => (child.nodeType === 3
    ? LETTER.test(child.data)
    : child.nodeType === 1 && !SKIP.has(child.localName) && hasLetters(child)));

  const isOpaque = (el) => {
    const tag = el.localName;
    if (OPAQUE_TAGS.has(tag)) return true;
    if (el.hasAttribute('data-i18n-keep') || el.hasAttribute('data-price') || el.hasAttribute('data-year')) return true;
    if (el.getAttribute('translate') === 'no') return true;
    if (isFixedKey(el.getAttribute('data-i18n'))) return true;
    if (tag === 'a' && /^(mailto|tel):/i.test(el.getAttribute('href') || '')) return true;
    return INLINE.has(tag) && !hasLetters(el);
  };

  const escapeText = (text) => String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/ /g, '&nbsp;');
  const decode = (text) => text.replace(/&(amp|lt|gt|nbsp);/g, (match, name) => ENTITY[name]);
  const markers = (text) => (text.match(/<\/?\d+\/?>/g) || []).sort().join(' ');

  /** The English text of a unit in placeholder form, and the element behind each number. */
  const serialize = (el) => {
    const elements = [null];
    const walk = (node) => {
      let out = '';
      node.childNodes.forEach((child) => {
        if (child.nodeType === 3) out += escapeText(child.data.replace(/[ \t\r\n\f]+/g, ' '));
        else if (child.nodeType === 1) {
          const n = elements.length;
          elements.push(child);
          out += isOpaque(child) ? `<${n}/>` : `<${n}>${walk(child)}</${n}>`;
        }
      });
      return out;
    };
    const text = walk(el).replace(/ {2,}/g, ' ');
    // A space at either end (" on WhatsApp" after a phone number) is kept round every language
    return { source: text.trim(), elements, lead: text.startsWith(' ') ? ' ' : '', trail: text.endsWith(' ') && text.trim() ? ' ' : '' };
  };

  /** Rebuilds a unit from text in placeholder form, reusing its own elements (and their listeners). */
  const render = (unit, text) => {
    const stack = [document.createDocumentFragment()];
    let pending = '';
    const flush = () => {
      if (pending) stack[stack.length - 1].append(pending);
      pending = '';
    };
    TOKEN.lastIndex = 0;
    let match;
    while ((match = TOKEN.exec(text))) {
      const [token, closing, number, selfClosing, entity] = match;
      if (number) {
        flush();
        const el = unit.elements[Number(number)];
        if (!el) continue;
        if (selfClosing) stack[stack.length - 1].append(el);
        else if (closing) { if (stack.length > 1 && stack[stack.length - 1] === el) stack.pop(); }
        else {
          el.replaceChildren();
          stack[stack.length - 1].append(el);
          stack.push(el);
        }
      } else {
        pending += entity ? ENTITY[entity] : token;
      }
    }
    flush();
    unit.el.replaceChildren(unit.lead, stack[0], unit.trail);
  };

  /* ---------- What is on the page ---------- */
  const units = [];
  const unitOf = new Map();
  const attrs = [];

  const scan = () => {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const { source, elements, lead, trail } = serialize(el);
      const unit = { el, key: el.getAttribute('data-i18n'), source, elements, lead, trail, markers: markers(source), shown: source };
      units.push(unit);
      unitOf.set(el, unit);
    });
    document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
      el.getAttribute('data-i18n-attr').split('|').forEach((pair) => {
        const at = pair.indexOf('=');
        if (at < 1) return;
        const name = pair.slice(0, at);
        const value = el.getAttribute(name);
        if (value !== null) attrs.push({ el, name, key: pair.slice(at + 1), source: value });
      });
    });
  };

  /* ---------- Language bundles ---------- */
  // Each bundle script calls window.__i18n.push({ lang, bundle, s, t, label }). The <head> script
  // starts loading the visitor's language before this file runs, so some may already be queued;
  // one that fails to load is pushed empty, so the page never waits for it.
  const data = {};
  const entry = (lang) => {
    if (!data[lang]) data[lang] = { bundles: {}, s: {}, t: {}, label: {} };
    return data[lang];
  };
  const ready = (lang) => lang === 'en' || bundlesFor.every((bundle) => entry(lang).bundles[bundle]);

  const bundleSrc = (lang, bundle) => `assets/i18n/${lang}/${bundle}.js`;
  const load = (lang) => {
    bundlesFor.forEach((bundle) => {
      if (entry(lang).bundles[bundle]) return;
      const src = bundleSrc(lang, bundle);
      if (Array.from(document.scripts).some((script) => script.getAttribute('src') === src)) return;
      const script = document.createElement('script');
      script.src = src;
      script.onerror = () => receive({ lang, bundle, s: {} });
      document.head.append(script);
    });
  };

  /* ---------- Switching ---------- */
  let wanted = 'en';
  let lang = 'en';

  const lookup = (key, target) => {
    if (target === 'en') return null;
    if (key.startsWith('t:')) {
      const message = data[target].t[key.slice(2)];
      return typeof message === 'string' ? escapeText(message) : null;
    }
    return data[target].s[key] ?? null;
  };

  const showUnit = (unit) => {
    let text = lookup(unit.key, lang);
    if (text === null && unit.key.startsWith('t:') && typeof EN[unit.key.slice(2)] === 'string') text = escapeText(EN[unit.key.slice(2)]);
    // A translation that lost or gained a marker would drop or duplicate markup: show the English.
    if (text === null || markers(text) !== unit.markers) text = unit.source;
    if (text === unit.shown) return;
    render(unit, text);
    unit.shown = text;
  };

  const showAttr = (item) => {
    const text = lookup(item.key, lang);
    const value = text === null ? item.source : decode(text);
    if (item.el.getAttribute(item.name) !== value) item.el.setAttribute(item.name, value);
  };

  const updateSwitchers = () => {
    document.querySelectorAll('[data-lang]').forEach((button) => {
      if (button.dataset.lang === lang) button.setAttribute('aria-current', 'true');
      else button.removeAttribute('aria-current');
    });
    document.querySelectorAll('[data-lang-code]').forEach((el) => { el.textContent = lang.toUpperCase(); });
    // The header button's flag: same folder, the chosen language's file
    document.querySelectorAll('[data-lang-flag]').forEach((el) => {
      el.setAttribute('src', el.getAttribute('src').replace(/[a-z]+\.svg$/, LANGS[lang].flag + '.svg'));
    });
  };

  const apply = () => {
    lang = wanted;
    root.lang = LANGS[lang].tag;
    root.dir = LANGS[lang].dir;
    units.forEach(showUnit);
    attrs.forEach(showAttr);
    updateSwitchers();
    root.classList.remove('i18n-pending', 'i18n-loading');
    document.dispatchEvent(new CustomEvent('i18n:change', { detail: { lang } }));
  };

  const set = (next) => {
    if (!LANGS[next]) next = 'en';
    try { window.localStorage.setItem(STORE_KEY, next); } catch (error) { /* not saved: still switches */ }
    wanted = next;
    if (next === lang) {
      // Back to the language already showing while another was still loading.
      root.classList.remove('i18n-loading');
      updateSwitchers();
      return;
    }
    if (ready(next)) apply();
    else {
      root.classList.add('i18n-loading');
      load(next);
    }
  };

  function receive(bundle) {
    if (!bundle || !LANGS[bundle.lang]) return;
    const target = entry(bundle.lang);
    target.bundles[bundle.bundle] = true;
    Object.assign(target.s, bundle.s);
    if (bundle.t) Object.assign(target.t, bundle.t);
    if (bundle.label) Object.assign(target.label, bundle.label);
    if (bundle.lang === wanted && wanted !== lang && ready(wanted)) apply();
  }

  /* ---------- Script text ---------- */
  const t = (name, vars = {}) => {
    let message = (lang !== 'en' && data[lang].t[name]) || EN[name];
    if (message === undefined) return name;
    if (message && typeof message === 'object') {
      const form = new Intl.PluralRules(LANGS[lang].tag).select(Number(vars.n) || 0);
      const own = lang !== 'en' && data[lang].t[name];
      message = (own && (own[form] || own.other)) || EN[name][form] || EN[name].other;
    }
    return String(message).replace(/\{(\w+)\}/g, (match, key) => (key in vars ? String(vars[key]) : match));
  };

  const label = (value) => (lang !== 'en' && data[lang].label[value]) || value;

  const refresh = (el) => {
    const unit = unitOf.get(el);
    if (!unit) return;
    unit.shown = null;
    showUnit(unit);
  };

  /* ---------- Language menus ---------- */
  const menus = Array.from(document.querySelectorAll('[data-lang-menu]')).map((menu) => {
    const toggle = menu.querySelector('.lang__toggle');
    const list = menu.querySelector('.lang__list');
    const options = () => Array.from(list.querySelectorAll('[data-lang]'));

    const setOpen = (open, { focus = false } = {}) => {
      if (open === !list.hidden) return;
      list.hidden = !open;
      toggle.setAttribute('aria-expanded', String(open));
      menu.classList.toggle('is-open', open);
      if (open && focus) (options().find((option) => option.dataset.lang === lang) || options()[0]).focus();
      if (!open && focus) toggle.focus();
    };

    toggle.addEventListener('click', () => {
      menus.forEach((other) => { if (other.menu !== menu) other.setOpen(false); });
      // A keyboard "click" (Enter or Space) moves focus into the list; a tap leaves it on the button.
      setOpen(list.hidden, { focus: list.hidden && toggle.matches(':focus-visible') });
    });

    list.addEventListener('click', (event) => {
      const option = event.target.closest('[data-lang]');
      if (!option) return;
      set(option.dataset.lang);
      setOpen(false, { focus: true });
    });

    menu.addEventListener('keydown', (event) => {
      if (event.key === 'Escape' && !list.hidden) {
        // Stops here, so the mobile menu behind stays open.
        event.stopPropagation();
        setOpen(false, { focus: true });
        return;
      }
      if (list.hidden) {
        if (event.target === toggle && (event.key === 'ArrowDown' || event.key === 'ArrowUp')) {
          event.preventDefault();
          setOpen(true, { focus: true });
        }
        return;
      }
      const all = options();
      const at = all.indexOf(document.activeElement);
      let next = -1;
      if (event.key === 'ArrowDown') next = at < 0 ? 0 : (at + 1) % all.length;
      else if (event.key === 'ArrowUp') next = at < 0 ? all.length - 1 : (at - 1 + all.length) % all.length;
      else if (event.key === 'Home') next = 0;
      else if (event.key === 'End') next = all.length - 1;
      if (next < 0) return;
      event.preventDefault();
      all[next].focus();
    });

    // Closes when focus or a tap goes anywhere else.
    menu.addEventListener('focusout', (event) => {
      if (event.relatedTarget && !menu.contains(event.relatedTarget)) setOpen(false);
    });

    return { menu, setOpen };
  });

  document.addEventListener('click', (event) => {
    menus.forEach(({ menu, setOpen }) => { if (!menu.contains(event.target)) setOpen(false); });
    const button = event.target.closest('[data-lang]');
    // The drawer's row of language buttons (the dropdowns handle their own above).
    if (button && !button.closest('[data-lang-menu]')) set(button.dataset.lang);
  });

  /* ---------- Start ---------- */
  scan();
  const queued = Array.isArray(window.__i18n) ? window.__i18n : [];
  window.__i18n = { push: (...bundles) => bundles.forEach(receive) };

  const query = /[?&]lang=([a-z]{2})(?:&|$)/.exec(window.location.search);
  let start = query && LANGS[query[1]] ? query[1] : null;
  if (start) {
    try { window.localStorage.setItem(STORE_KEY, start); } catch (error) { /* this page only */ }
  } else {
    try { start = window.localStorage.getItem(STORE_KEY); } catch (error) { start = null; }
  }
  wanted = LANGS[start] ? start : 'en';
  queued.forEach(receive);
  if (wanted !== 'en' && wanted !== lang) {
    if (ready(wanted)) apply();
    else load(wanted);
  }
  updateSwitchers();

  window.i18n = {
    get lang() { return lang; },
    languages: LANGS,
    set,
    t,
    label,
    refresh,
  };
})();
